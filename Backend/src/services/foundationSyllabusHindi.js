export function localizeDurationChip(chip, medium) {
  if (medium !== "hi" || !chip) return chip;
  return String(chip)
    .replace(/\bmodules?\b/gi, "मॉड्यूल")
    .replace(/\bmonths?\b/gi, "महीने")
    .replace(/\bweeks?\b/gi, "सप्ताह")
    .replace(/\bdays?\b/gi, "दिन")
    .replace(/\bh\b/g, "घं");
}

export function getSubjectName(subjectKey, englishName, medium = "en") {
  if (medium === "hi") {
    return SUBJECT_NAME_HI[subjectKey] || englishName;
  }
  return englishName;
}

export function getModuleName(moduleId, englishName, medium = "en") {
  if (medium === "hi") {
    return MODULE_NAME_HI[String(moduleId)] || englishName;
  }
  return englishName;
}

export function formatChapterPreview(chapter, name, medium = "en", nameAlt = "") {
  const ch = chapter ? String(chapter) : "";
  const primary = String(name || "").trim();
  const alt = String(nameAlt || "").trim();
  if (medium === "hi") {
    const bilingual =
      alt && alt !== primary ? `${primary} (${alt})` : primary;
    return ch ? `अध्याय ${ch}: ${bilingual}` : bilingual;
  }
  if (alt && alt !== primary) {
    return ch ? `Ch ${ch}: ${primary} (${alt})` : `${primary} (${alt})`;
  }
  return ch ? `Ch ${ch}: ${primary}` : primary;
}

/** Resolve display chapter name for a given medium. */
export function resolveChapterDisplayName(chapterObj, medium = "en") {
  if (!chapterObj) return "";
  const lang = normalizeMedium(medium);
  if (lang === "hi") {
    return chapterObj.nameHi || chapterObj.name || chapterObj.nameEn || "";
  }
  return chapterObj.nameEn || chapterObj.name || "";
}

export function normalizeMedium(value) {
  return String(value || "").toLowerCase() === "hi" ? "hi" : "en";
}
